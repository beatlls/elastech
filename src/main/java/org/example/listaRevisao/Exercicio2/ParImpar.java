package org.example.listaRevisao.Exercicio2;

public class ParImpar {
    public static void main(String[] args) {
        for (int i = 0; i <= 15; i++) {
            if (i % 2 == 0) {
                System.out.println(i + " é par.");
            } else {
                System.out.println(i + " é ímpar.");
            }
        }
    }
}
