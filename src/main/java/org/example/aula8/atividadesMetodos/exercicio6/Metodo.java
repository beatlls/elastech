package org.example.aula8.atividadesMetodos.exercicio6;

public class Metodo {
    static void somar(int num1, int num2) {
        int soma = num1 + num2;
        System.out.println(soma);
    }

    static void somar(int num1, int num2, int num3) {
        int soma = num1 + num2 + num3;
        System.out.println(soma);
    }

    static void somar(double num1, double num2) {
        double soma = num1 + num2;
        System.out.println(soma);
    }
}
