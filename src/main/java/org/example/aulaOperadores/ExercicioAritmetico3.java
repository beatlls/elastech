package org.example.aulaOperadores;

public class ExercicioAritmetico3 {
    public static void main(String[] args) {
        // 3- Crie variáveis para três notas (8, 6 e 10). Mostre a soma e a média.

        int notaA = 8;
        int notaB = 6;
        int notaC = 10;
        int media = 0;

        media = (notaA + notaB + notaC) / 3;

        System.out.println("A média das três notas é: " + media);
    }
}
